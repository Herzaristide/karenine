//! Reversal-Accent — the Reversal icon theme recoloured to the accent.
//!
//! The source theme is a store path handed over by the Nix wrapper
//! (`ANNA_ICON_SOURCE`, …/share/icons). Reversal is ~160 MB of SVGs, so
//! nothing is copied: the generated theme under
//! `~/.local/share/icons/Reversal-Accent` symlinks every context back to the
//! source (Reversal-dark, or Reversal in light mode) except `apps/scalable`
//! and `places/scalable`, rewritten in "mono": every saturated colour takes
//! the accent hue (see `Color::mono_toward`), so icons keep their relief and
//! stay recognisable by shape.
//!
//! Qt caches theme icons (`QIcon::fromTheme`) for the life of the process,
//! whatever the file on disk becomes, so Quickshell would keep the previous
//! accent. Each generation therefore also writes a manifest,
//! `$XDG_RUNTIME_DIR/anna-icons.json` (name → recoloured file, plus a
//! revision), that karenine's `Theme.icon()` turns into `file://…?rev=` URLs
//! to load those icons straight from disk.

use crate::color::Color;
use crate::paths;
use crate::state::AppState;
use std::collections::BTreeMap;
use std::fs;
use std::io;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};
use std::process::Command;

pub const THEME_NAME: &str = "Reversal-Accent";

/// Contexts whose scalable icons are recoloured; everything else is linked.
const RECOLOR: [&str; 2] = ["apps", "places"];

/// Icons whose identity lives in several hues and that turn to mush once
/// flattened to one: kept as they are (prefix match on the file name, so
/// "firefox" also covers firefox-aurora, firefox-developer…).
const KEEP: [&str; 2] = ["firefox", "krita"];

/// Regenerate the theme if the accent, mode or source changed since the last
/// run, then (re)write the manifest. Returns whether the theme was rebuilt.
pub fn refresh(state: &AppState) -> io::Result<bool> {
    let Some(base) = std::env::var_os("ANNA_ICON_SOURCE").map(PathBuf::from) else {
        return Ok(false);
    };
    let variant = if state.mode == "light" {
        "Reversal"
    } else {
        "Reversal-dark"
    };
    let src = base.join(variant);
    let root = paths::home_dir().join(".local/share/icons");
    let dest = root.join(THEME_NAME);
    let stamp = format!(
        "{} {} {}",
        state.accent.hex_no_hash(),
        state.mode,
        src.display()
    );
    let manifest = PathBuf::from(paths::runtime_dir()).join("anna-icons.json");

    let current = fs::read_to_string(dest.join(".anna-stamp")).unwrap_or_default();
    let rebuilt = current != stamp;
    if rebuilt {
        build(&src, &root, &state.accent, &stamp)?;
    } else if manifest.exists() {
        return Ok(false);
    }
    write_manifest(&dest, &manifest, &state.accent, &state.mode)?;
    Ok(rebuilt)
}

fn build(src: &Path, root: &Path, accent: &Color, stamp: &str) -> io::Result<()> {
    let tmp = root.join(format!(".{THEME_NAME}.tmp"));
    let old = root.join(format!(".{THEME_NAME}.old"));
    let dest = root.join(THEME_NAME);
    for d in [&tmp, &old] {
        let _ = fs::remove_dir_all(d);
    }
    fs::create_dir_all(&tmp)?;

    let index = fs::read_to_string(src.join("index.theme"))?
        .lines()
        .map(|l| {
            if l.starts_with("Name=") {
                format!("Name={THEME_NAME}")
            } else if l.starts_with("Comment=") {
                "Comment=Reversal recoloured to the accent (generated by anna)".into()
            } else {
                l.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n");
    fs::write(tmp.join("index.theme"), index + "\n")?;

    for entry in fs::read_dir(src)?.flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        let path = entry.path();
        if name == "index.theme" || name == "icon-theme.cache" {
            continue;
        }
        if RECOLOR.contains(&name.as_str()) {
            fs::create_dir(tmp.join(&name))?;
            for sub in fs::read_dir(&path)?.flatten() {
                let sub_name = sub.file_name();
                let out = tmp.join(&name).join(&sub_name);
                if sub_name == "scalable" {
                    recolor_dir(&fs::canonicalize(sub.path())?, &out, accent)?;
                } else {
                    symlink(fs::canonicalize(sub.path())?, out)?;
                }
            }
        } else if let Some(ctx) = name.strip_suffix("@2x").filter(|c| RECOLOR.contains(c)) {
            symlink(ctx, tmp.join(&name))?;
        } else {
            symlink(fs::canonicalize(&path)?, tmp.join(&name))?;
        }
    }
    fs::write(tmp.join(".anna-stamp"), stamp)?;

    // Swap in place so readers never see a half-written theme.
    if dest.exists() {
        fs::rename(&dest, &old)?;
    }
    fs::rename(&tmp, &dest)?;
    let _ = fs::remove_dir_all(&old);

    let _ = Command::new("gtk-update-icon-cache")
        .args(["-q", "-f"])
        .arg(&dest)
        .output();
    Ok(())
}

fn recolor_dir(src: &Path, out: &Path, accent: &Color) -> io::Result<()> {
    fs::create_dir(out)?;
    for f in fs::read_dir(src)?.flatten() {
        let name = f.file_name().to_string_lossy().to_string();
        let path = f.path();
        let target = out.join(&name);
        let link = fs::read_link(&path).ok();
        // KEEP is tested first: krita.svg is itself an alias of calligrakrita.svg.
        if !name.ends_with(".svg") || KEEP.iter().any(|k| name.starts_with(k)) {
            symlink(resolve(&path), target)?;
        } else if let Some(rel) = link.filter(|l| l.components().count() == 1) {
            // Other aliases inside the same directory stay aliases (to our
            // recoloured file). Upstream ships some dangling ones; kept as is.
            symlink(rel, target)?;
        } else {
            fs::write(target, recolor_svg(&fs::read(&path)?, accent))?;
        }
    }
    Ok(())
}

/// `canonicalize`, or the path itself when it dangles.
fn resolve(path: &Path) -> PathBuf {
    fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf())
}

/// Rewrite the colours in paint positions (`fill`, `stroke`, `*-color`, as an
/// attribute or a CSS property). A bare `#abc` elsewhere may be a `url(#id)`.
pub fn recolor_svg(svg: &[u8], accent: &Color) -> Vec<u8> {
    let mut out = Vec::with_capacity(svg.len());
    let mut i = 0;
    while i < svg.len() {
        if svg[i] == b'#' && in_paint_position(&svg[..i]) {
            let len = svg[i + 1..]
                .iter()
                .take_while(|b| b.is_ascii_hexdigit())
                .count();
            let boundary = svg
                .get(i + 1 + len)
                .is_none_or(|b| !(b.is_ascii_alphanumeric() || *b == b'_'));
            if (len == 6 || len == 3) && boundary {
                let hex = std::str::from_utf8(&svg[i + 1..i + 1 + len]).unwrap_or_default();
                let full: String = if len == 3 {
                    hex.chars().flat_map(|c| [c, c]).collect()
                } else {
                    hex.to_string()
                };
                if let Some(c) = Color::from_hex(&full) {
                    out.extend_from_slice(c.mono_toward(accent).to_hex().as_bytes());
                    i += 1 + len;
                    continue;
                }
            }
        }
        out.push(svg[i]);
        i += 1;
    }
    out
}

/// Whether the text before a `#` ends with `fill=`, `stroke:`, `stop-color="`…
fn in_paint_position(before: &[u8]) -> bool {
    let mut end = before.len();
    if end > 0 && matches!(before[end - 1], b'"' | b'\'') {
        end -= 1;
    }
    while end > 0 && before[end - 1].is_ascii_whitespace() {
        end -= 1;
    }
    if end == 0 || !matches!(before[end - 1], b':' | b'=') {
        return false;
    }
    end -= 1;
    while end > 0 && before[end - 1].is_ascii_whitespace() {
        end -= 1;
    }
    let start = before[..end]
        .iter()
        .rposition(|b| !(b.is_ascii_alphabetic() || *b == b'-'))
        .map_or(0, |p| p + 1);
    let ident = &before[start..end];
    [&b"fill"[..], b"stroke", b"color"]
        .iter()
        .any(|k| ident.ends_with(k))
}

/// Name → file (relative to the theme) for every recoloured context, so
/// karenine can load them without going through Qt's icon cache.
fn write_manifest(dest: &Path, manifest: &Path, accent: &Color, mode: &str) -> io::Result<()> {
    let mut icons = BTreeMap::new();
    for ctx in RECOLOR {
        let dir = dest.join(ctx).join("scalable");
        let Ok(entries) = fs::read_dir(&dir) else {
            continue;
        };
        for f in entries.flatten() {
            let name = f.file_name().to_string_lossy().to_string();
            // `exists` follows links: dangling upstream aliases are skipped.
            if let (Some(stem), true) = (name.strip_suffix(".svg"), f.path().exists()) {
                icons
                    .entry(stem.to_string())
                    .or_insert_with(|| format!("{ctx}/scalable/{name}"));
            }
        }
    }
    let json = serde_json::json!({
        "rev": format!("{}-{mode}", accent.hex_no_hash()),
        "root": dest,
        "icons": icons,
    });
    fs::write(manifest, json.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn recolor(s: &str) -> String {
        let accent = Color::from_hex("#459f50").unwrap();
        String::from_utf8(recolor_svg(s.as_bytes(), &accent)).unwrap()
    }

    #[test]
    fn recolours_paint_positions_only() {
        let accent = Color::from_hex("#459f50").unwrap();
        let red = Color::from_hex("#f05050")
            .unwrap()
            .mono_toward(&accent)
            .to_hex();
        assert_eq!(recolor(r##"fill="#f05050""##), format!(r#"fill="{red}""#));
        assert_eq!(
            recolor("style=\"stop-color:#f05050\""),
            format!("style=\"stop-color:{red}\"")
        );
        assert_eq!(recolor("stroke = '#f05050'"), format!("stroke = '{red}'"));
        // Ids, hrefs and unrelated attributes are left alone.
        assert_eq!(recolor(r##"fill="url(#abc)""##), r##"fill="url(#abc)""##);
        assert_eq!(recolor(r##"href="#f05050""##), r##"href="#f05050""##);
        assert_eq!(recolor(r##"fill="#f05050ff""##), r##"fill="#f05050ff""##);
    }

    #[test]
    fn expands_short_hex_and_keeps_white() {
        assert_eq!(recolor(r##"fill="#fff""##), r##"fill="#ffffff""##);
        assert!(!recolor(r##"fill="#f50""##).contains("#f50\""));
    }
}
